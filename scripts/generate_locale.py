r"""Generate an ASCII Tcl catalog; \u escapes avoid Capture code-page ambiguity."""
from pathlib import Path
import json

BASE = Path(__file__).resolve().parents[1]


def quote(value):
    text = json.dumps(value, ensure_ascii=True)
    return text.replace('$', r'\$').replace('[', r'\[').replace(']', r'\]')


def main():
    data = json.loads((BASE / 'src/zh_CN.json').read_text(encoding='utf-8'))
    lines = ['# Generated by scripts/generate_locale.py from src/zh_CN.json.',
             '# ASCII source, Unicode values. Do not change the system encoding.',
             'namespace eval ::TriExport {', '    variable zhExact [dict create]','    variable zhPatterns {}']
    for key, value in data['exact'].items():
        lines.append(f'    dict set zhExact {quote(key)} {quote(value)}')
    for pattern, value in data['patterns']:
        lines.append(f'    lappend zhPatterns [list {quote(pattern)} {quote(value)}]')
    lines.append('}')
    (BASE / 'src/ZhCN.tcl').write_text('\n'.join(lines) + '\n', encoding='ascii')


if __name__ == '__main__':
    main()
